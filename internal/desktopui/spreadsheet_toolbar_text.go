func (a *App) localizedSpreadsheetToolbarText(value string) string {
	if message, ok := spreadsheetToolbarTextMessages[value]; ok {
		return a.text(message)
	}
	return value
}

func (a *App) localizedSpreadsheetToolbarCategoryLabels(state *documentSessionState) []string {
	labels := toolbarCategoryLabelsForState(state)
	for index := range labels {
		labels[index] = a.localizedSpreadsheetToolbarText(labels[index])
	}
	return labels
}
